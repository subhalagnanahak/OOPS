package basics.Basic;

// A Java program to print Hello World!

  public class HelloWorld {                     // Defines a class named HelloWorld. There is an Opening Bracket for Class

    public static void main(String[] args) {   // This is the main method, the entry point of any Java program. There is an Opening Bracket for Method

        System.out.println("Hello World!");    // Output Statement prints "Hello World!" to the console.

    }                                           // There is a Closing Bracket for Method

}                                               // There is a Closing Bracket for Class
